/**
 * Dynamic colour is **off by default**, and that is a deliberate trade rather than an
 * oversight. The screen's status colours have to mean something specific (in range, out of
 * range, degraded fix), and a wallpaper-derived scheme can shift the primary close enough to
 * a status hue to blur that distinction. A reviewer opening the app on any device should
 * also see the palette this submission actually designed. The parameter stays available for
 * anyone who wants the platform behaviour back.
 */
@Composable
fun PresenceLensAttendanceTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val statusColors = if (darkTheme) DarkStatusColors else LightStatusColors

    CompositionLocalProvider(LocalStatusColors provides statusColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content
        )
    }
}

/** Success and warning roles, alongside `MaterialTheme.colorScheme`. */
object AttendanceTheme {
    val statusColors: StatusColors
        @Composable @ReadOnlyComposable get() = LocalStatusColors.current
}
